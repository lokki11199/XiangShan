#!/usr/bin/env python3
"""Port table of the Chisel bench CoreResetDCacheHarness (elab/CoreResetDCacheHarness.scala) and what is made of it.

The table is the one place where the stand (tb_rtl/dcache_tb.sv) and the bench agree on names, directions and widths.
Widths come from params.svh, which the bench writes at elaboration (nothing is typed by hand).

usage: dcache_ports.py decl  <params.svh> <out.svh>      logic declaration of every port (name = port name)
       dcache_ports.py inst  <params.svh> <out.svh>      instance `CoreResetDCacheHarness dut (...)` (clock, reset by the stand)
       dcache_ports.py stub  <params.svh> <out.sv>       a stub module with these ports (lint of the stand without RTL)
       dcache_ports.py check <params.svh> <rtl_dir>      compare the table with the generated RTL: names, directions,
                                                         widths; ports of the RTL missing in the table are listed
Exit code 1 when `check` finds a missing port or a different direction or width.
"""
import os
import re
import sys

TOP = "CoreResetDCacheHarness"


def read_params(path):
    P = {}
    with open(path) as f:
        for ln in f:
            m = re.match(r"\s*localparam\s+int\s+(\w+)\s*=\s*(-?\d+)\s*;", ln)
            if m:
                P[m.group(1)] = int(m.group(2))
    need = ("NSETS", "NWAYS", "BLOCK_BYTES", "BEAT_BYTES", "SRC_BITS", "SNK_BITS", "ADDR_BITS", "SIZE_BITS",
            "PADDR_BITS", "REQ_ID_BITS", "QUAD_BITS")
    miss = [k for k in need if k not in P]
    if miss:
        raise SystemExit("params.svh lacks %s" % ", ".join(miss))
    return P


def table(P):
    """[(name, 'input'|'output', width)] without clock and reset."""
    L = []

    def i(n, w=1):
        L.append((n, "input", w))

    def o(n, w=1):
        L.append((n, "output", w))

    # reset tree and controller side
    i("core_reset"); o("core_in_reset")
    i("quiesce_req"); i("quiesce_freeze"); o("quiesce_done"); o("quiesce_idle"); o("quiesce_alive")
    i("gate_block"); i("gate_holdB"); i("gate_ackB"); i("gate_isolate"); o("gate_quiet")
    # store
    i("st_req_valid"); o("st_req_ready"); i("st_req_addr", P["PADDR_BITS"])
    i("st_req_data", P["BLOCK_BYTES"] * 8); i("st_req_mask", P["BLOCK_BYTES"]); i("st_req_id", P["REQ_ID_BITS"])
    o("st_hit_valid"); o("st_hit_id", P["REQ_ID_BITS"]); o("st_replay_valid"); o("st_replay_id", P["REQ_ID_BITS"])
    # atomics
    i("amo_req_valid"); o("amo_req_ready"); i("amo_cmd", 5); i("amo_addr", P["PADDR_BITS"])
    i("amo_data", P["QUAD_BITS"]); i("amo_mask", P["QUAD_BITS"] // 8); i("amo_cmp", P["QUAD_BITS"])
    o("amo_resp_valid"); o("amo_resp_data", P["QUAD_BITS"]); o("amo_resp_miss"); o("amo_resp_replay")
    o("amo_resp_id", P["REQ_ID_BITS"]); o("amo_block_lr")
    # CMO
    i("cmo_req_valid"); o("cmo_req_ready"); i("cmo_opcode", 3); i("cmo_address", 64)
    o("cmo_resp_valid"); i("cmo_resp_ready"); o("cmo_resp_address", 64); o("cmo_resp_err")
    # WFI
    i("wfi_req"); o("wfi_safe")
    # load
    i("ld_req_valid"); o("ld_req_ready"); i("ld_req_addr", P["PADDR_BITS"])
    o("ld_resp_valid"); o("ld_resp_miss"); o("ld_resp_replay"); o("ld_resp_data", 64); o("ld_s2_hit"); o("ld_resp_err")
    # TL-C towards L2: the bench is the client, so A, C, E leave it and B, D come in
    sz, src, snk, ad = P["SIZE_BITS"], P["SRC_BITS"], P["SNK_BITS"], P["ADDR_BITS"]
    dw, mw = P["BEAT_BYTES"] * 8, P["BEAT_BYTES"]
    o("l2io_0_a_valid"); i("l2io_0_a_ready")
    o("l2io_0_a_bits_opcode", 4); o("l2io_0_a_bits_param", 3); o("l2io_0_a_bits_size", sz); o("l2io_0_a_bits_source", src)
    o("l2io_0_a_bits_address", ad); o("l2io_0_a_bits_mask", mw); o("l2io_0_a_bits_data", dw); o("l2io_0_a_bits_corrupt")
    i("l2io_0_b_valid"); o("l2io_0_b_ready")
    i("l2io_0_b_bits_opcode", 3); i("l2io_0_b_bits_param", 2); i("l2io_0_b_bits_size", sz); i("l2io_0_b_bits_source", src)
    i("l2io_0_b_bits_address", ad); i("l2io_0_b_bits_mask", mw); i("l2io_0_b_bits_data", dw); i("l2io_0_b_bits_corrupt")
    o("l2io_0_c_valid"); i("l2io_0_c_ready")
    o("l2io_0_c_bits_opcode", 3); o("l2io_0_c_bits_param", 3); o("l2io_0_c_bits_size", sz); o("l2io_0_c_bits_source", src)
    o("l2io_0_c_bits_address", ad); o("l2io_0_c_bits_data", dw); o("l2io_0_c_bits_corrupt")
    i("l2io_0_d_valid"); o("l2io_0_d_ready")
    i("l2io_0_d_bits_opcode", 4); i("l2io_0_d_bits_param", 2); i("l2io_0_d_bits_size", sz); i("l2io_0_d_bits_source", src)
    i("l2io_0_d_bits_sink", snk); i("l2io_0_d_bits_denied"); i("l2io_0_d_bits_data", dw); i("l2io_0_d_bits_corrupt")
    o("l2io_0_e_valid"); i("l2io_0_e_ready"); o("l2io_0_e_bits_sink", snk)
    return L


def decl(P):
    s = "// generated by scripts/dcache_ports.py: ports of %s\n" % TOP
    for n, d, w in table(P):
        s += "logic %s%s;\n" % ("[%d:0] " % (w - 1) if w > 1 else "", n)
    return s


def inst(P):
    s = "// generated by scripts/dcache_ports.py\n%s dut (\n  .clock(clk), .reset(dut_reset)" % TOP
    for n, d, w in table(P):
        s += ",\n  .%s(%s)" % (n, n)
    return s + "\n);\n"


def stub(P):
    ports = [("clock", "input", 1), ("reset", "input", 1)] + table(P)
    s = "// stub of %s for lint only (scripts/dcache_ports.py stub)\nmodule %s (\n" % (TOP, TOP)
    s += ",\n".join("  %s %s%s" % (d, "[%d:0] " % (w - 1) if w > 1 else "", n) for n, d, w in ports)
    s += "\n);\n"
    for n, d, w in ports:
        if d == "output":
            s += "  assign %s = '0;\n" % n
    # observable hierarchy used by the generated probes: the stub only has to exist
    return s + "endmodule\n"


def parse_rtl_ports(rtl_dir):
    hdr = re.compile(r"^module\s+%s\s*\((.*?)\);" % TOP, re.S | re.M)
    for root, _, files in os.walk(rtl_dir):
        for fn in sorted(files):
            if fn.endswith((".sv", ".v")):
                t = open(os.path.join(root, fn), errors="replace").read()
                t = re.sub(r"//[^\n]*", "", t)
                m = hdr.search(t)
                if m:
                    res = {}
                    for pm in re.finditer(r"(input|output|inout)\s+(?:\[(\d+):(\d+)\]\s*)?(\w+)", m.group(1)):
                        w = int(pm.group(2)) - int(pm.group(3)) + 1 if pm.group(2) else 1
                        res[pm.group(4)] = (pm.group(1), w)
                    return res
    raise SystemExit("module %s not found under %s" % (TOP, rtl_dir))


def check(P, rtl_dir):
    have = parse_rtl_ports(rtl_dir)
    bad = 0
    for n, d, w in [("clock", "input", 1), ("reset", "input", 1)] + table(P):
        if n not in have:
            print("MISSING port %s (%s, %d bits)" % (n, d, w)); bad += 1
        elif have[n] != (d, w):
            print("DIFFERENT port %s: table %s/%d, RTL %s/%d" % (n, d, w, have[n][0], have[n][1])); bad += 1
    known = {n for n, _, _ in table(P)} | {"clock", "reset"}
    extra = sorted(n for n in have if n not in known)
    # user / echo fields of the TL channels are left unconnected by the stand on purpose
    extra_other = [n for n in extra if not re.match(r"l2io_0_[a-e]_bits_(user|echo)_", n)]
    if extra_other:
        print("note: ports of the RTL that the stand does not use: " + ", ".join(extra_other))
    print("check %s: %s (%d ports in the table)" % (TOP, "FAIL" if bad else "OK", len(table(P)) + 2))
    return 1 if bad else 0


def main():
    if len(sys.argv) != 4 or sys.argv[1] not in ("decl", "inst", "stub", "check"):
        raise SystemExit(__doc__)
    P = read_params(sys.argv[2])
    cmd = sys.argv[1]
    if cmd == "check":
        sys.exit(check(P, sys.argv[3]))
    text = {"decl": decl, "inst": inst, "stub": stub}[cmd](P)
    with open(sys.argv[3], "w") as f:
        f.write(text)


if __name__ == "__main__":
    main()
